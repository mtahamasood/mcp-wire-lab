"""G10: generate docs/atlas.md, the message atlas, from the pinned schemas and the lessons.

One row per method of the two target revisions: kind, direction (from membership in the
schema's ClientRequest, ServerRequest, ClientNotification and ServerNotification unions), the
revisions that define it, and the lessons that declare it with one line
`<!-- exercises: <method>, <method>, ... -->`. Never reads run output.

Usage: python3 tools/atlas.py [--check] [repo-root]
  (no flag)  write docs/atlas.md
  --check    exit 1 if docs/atlas.md differs from a fresh render, or a lesson declares a
             method no schema defines
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # run as a script: find `tools`

from tools.check_lessons import _strip_fences  # noqa: E402

REVISIONS = ("2025-11-25", "2026-07-28")
UNIONS = (
    ("ClientRequest", "request", "client to server"),
    ("ServerRequest", "request", "server to client"),
    ("ClientNotification", "notification", "client to server"),
    ("ServerNotification", "notification", "server to client"),
    # 2026-07-28 has no ServerRequest: the server asks the client through a result instead.
    ("InputRequest", "request", "server to client, inside an InputRequiredResult"),
)
DECLARATION = re.compile(r"<!--\s*exercises:(.*?)-->", re.DOTALL)
ATLAS = Path("docs/atlas.md")
INTRO = """# Message atlas

This file is generated by `tools/atlas.py` from the pinned schemas of revisions
{revisions} (`vendor/spec/schema/<revision>/schema.json`) and from the lessons' declarations.
Do not edit it. Regenerate it with `python3 tools/atlas.py`; gate G10 runs
`python3 tools/atlas.py --check` and fails when this file is stale.

- **Kind and direction** come from membership in the schema's `ClientRequest`,
  `ServerRequest`, `ClientNotification` and `ServerNotification` unions, plus `InputRequest`
  (2026-07-28 has no `ServerRequest`; its server-to-client requests travel inside an
  `InputRequiredResult`).
- **Lessons** lists the lessons whose line `<!-- exercises: <method>, ... -->` declares the
  method. A declaration is checked against a fresh trace of the lesson's recording in
  `tests/test_e2e.py`. A method no lesson declares is marked `unexercised`.
- The capability that gates each method is deliberately omitted: the schemas do not encode it
  (an accepted limit, phase 3 D6).

Counts: {counts}.

| Method | Kind | Direction | Revisions | Lessons |
| --- | --- | --- | --- | --- |
"""


def _defs(root: Path, revision: str) -> dict[str, Any]:
    path = root / "vendor/spec/schema" / revision / "schema.json"
    defs: dict[str, Any] = json.loads(path.read_text("utf-8"))["$defs"]
    return defs


def _union_methods(defs: dict[str, Any], union: str) -> list[str]:
    """Methods of a union def: its anyOf members, or (2026-07-28 ClientNotification, which has
    a single member) the def itself. An absent union has none; any other shape is an error."""
    node = defs.get(union)
    if node is None:
        return []
    if "anyOf" in node:
        return [str(defs[m["$ref"].rsplit("/", 1)[1]]["properties"]["method"]["const"])
                for m in node["anyOf"]]
    if "const" in node.get("properties", {}).get("method", {}):
        return [str(node["properties"]["method"]["const"])]
    raise ValueError(f"{union}: neither an anyOf union nor a single method definition")


def schema_methods(root: Path) -> dict[str, dict[str, tuple[str, str]]]:
    """method -> {revision: (kind, direction)}; a method in both client and server unions
    (ping, notifications/cancelled) has direction "client to server and server to client"."""
    found: dict[str, dict[str, tuple[str, str]]] = {}
    for revision in REVISIONS:
        defs = _defs(root, revision)
        for union, kind, direction in UNIONS:
            for method in _union_methods(defs, union):
                previous = found.setdefault(method, {}).get(revision)
                found[method][revision] = (
                    kind, direction if previous is None else f"{previous[1]} and {direction}"
                )
    return found


def declared_methods(root: Path) -> dict[str, list[str]]:
    """lesson file name -> methods it declares (only lessons with a declaration)."""
    out: dict[str, list[str]] = {}
    for lesson in sorted((root / "docs/lessons").glob("*.md")):
        prose = _strip_fences(lesson.read_text(encoding="utf-8"))
        methods = [m.strip() for d in DECLARATION.findall(prose) for m in d.split(",")]
        methods = [m for m in methods if m]
        if methods:
            out[lesson.name] = methods
    return out


def _cell(per_revision: dict[str, tuple[str, str]], index: int) -> str:
    values = {revision: v[index] for revision, v in per_revision.items()}
    if len(set(values.values())) == 1:
        return next(iter(values.values()))
    return "; ".join(f"{r}: {v}" for r, v in values.items())


def render(root: Path) -> str:
    methods = schema_methods(root)
    declared = declared_methods(root)
    counts = ", ".join(
        f"{r}: {sum(r in per for per in methods.values())} methods" for r in REVISIONS
    )
    rows: list[str] = []
    for method in sorted(methods):
        per = methods[method]
        lessons = [
            f"[{name.split('-')[0]}](lessons/{name})"
            for name, declares in declared.items()
            if method in declares
        ]
        rows.append(
            f"| `{method}` | {_cell(per, 0)} | {_cell(per, 1)} | "
            f"{', '.join(r for r in REVISIONS if r in per)} | "
            f"{', '.join(lessons) if lessons else 'unexercised'} |"
        )
    head = INTRO.format(revisions=" and ".join(REVISIONS), counts=counts)
    return head + "\n".join(rows) + "\n"


def check(root: Path) -> list[str]:
    errors: list[str] = []
    known = schema_methods(root)
    for name, declares in declared_methods(root).items():
        for method in declares:
            if method not in known:
                errors.append(f"{name} declares unknown method {method!r}: no schema defines it")
    if errors:
        return errors
    path = root / ATLAS
    if not path.is_file() or path.read_text(encoding="utf-8") != render(root):
        errors.append(f"{ATLAS} is stale or missing: run `python3 tools/atlas.py` and commit it")
    return errors


def main(argv: list[str]) -> int:
    args = argv[1:]
    check_only = args[:1] == ["--check"]
    if check_only:
        args = args[1:]
    root = Path(args[0]) if args else Path(__file__).resolve().parent.parent
    if check_only:
        errors = check(root)
        for e in errors:
            print(f"atlas: {e}", file=sys.stderr)
        if errors:
            return 1
        print("atlas: ok")
        return 0
    known = schema_methods(root)
    bad = [
        f"{name} declares unknown method {m!r}"
        for name, declares in declared_methods(root).items()
        for m in declares
        if m not in known
    ]
    if bad:
        for e in bad:
            print(f"atlas: {e}", file=sys.stderr)
        return 1
    (root / ATLAS).write_text(render(root), encoding="utf-8")
    print(f"atlas: wrote {ATLAS}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
